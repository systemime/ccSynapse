// Behavioural tests for the one piece of genuinely new logic: turning Claude
// Code's on-disk transcript into the projection events the canvas consumes.
// The fixtures mirror shapes observed on a real machine, including the awkward
// ones (metadata lines first, one API message split across several lines).

import { test } from 'node:test'
import assert from 'node:assert/strict'
import { mkdtemp, mkdir, writeFile, appendFile, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

import { TranscriptSource, detectForks, promptText } from '../server/transcript.js'

/** Minimal stand-in for WorkspaceStore that records what the projector emits. */
function stubStore() {
  return {
    calls: [],
    projected: [],
    async projectSession(session, replayFrom, title) { this.calls.push(['session', session.id, title]); this.projected.push(...session.events) },
    async projectEvents(session, events, title) { this.calls.push(['events', session.id, title]); this.projected.push(...events) },
  }
}

async function fixture(lines) {
  const root = await mkdtemp(join(tmpdir(), 'ccsynapse-'))
  const project = join(root, 'F--Project-Demo')
  await mkdir(project, { recursive: true })
  const file = join(project, 'aaaaaaaa-1111-2222-3333-444444444444.jsonl')
  await writeFile(file, lines.map(line => `${JSON.stringify(line)}\n`).join(''), 'utf8')
  return { root, file, cleanup: () => rm(root, { recursive: true, force: true }) }
}

const userLine = (text) => ({ type: 'user', uuid: 'u1', timestamp: '2026-01-01T00:00:00.000Z', cwd: 'F:\\Project\\Demo', sessionId: 's1', message: { role: 'user', content: text } })
const assistantLine = (id, index, block) => ({ type: 'assistant', uuid: `a${index}`, timestamp: '2026-01-01T00:00:01.000Z', cwd: 'F:\\Project\\Demo', sessionId: 's1', message: { id, role: 'assistant', content: [block] } })

test('metadata lines lead the file, so cwd must be found later', async () => {
  const { root, cleanup } = await fixture([
    { type: 'last-prompt', leafUuid: 'x', sessionId: 's1' },       // no cwd at all
    { type: 'mode', mode: 'normal', sessionId: 's1' },
    userLine('你好'),
  ])
  try {
    const store = stubStore()
    const source = new TranscriptSource(root)
    await source.sync(store, 'T')
    // The 43-of-63 trap: assuming line 0 carries cwd would drop this session.
    assert.equal(store.calls.length, 1, 'session projected exactly once')
    assert.deepEqual(store.calls[0], ['session', 'aaaaaaaa-1111-2222-3333-444444444444', 'T'])
    const [event] = store.projected
    assert.equal(event.type, 'user/message')
    assert.equal(event.seq, 2, 'seq is the file line index, metadata included')
  } finally { await cleanup() }
})

test('injected scaffolding is not a user turn, but a slash command keeps its arguments', async () => {
  const { root, cleanup } = await fixture([
    userLine('<command-name>/model</command-name>\n<command-message>model</command-message>\n<command-args></command-args>'),
    userLine('<local-command-stdout>Enabled plan mode</local-command-stdout>'),
    userLine('<local-command-caveat>Caveat: The messages below were generated by the user.</local-command-caveat>'),
    // Up to 32 KB per line in the real corpus; must never become a card.
    userLine('<task-notification><task-id>abc</task-id><status>completed</status><result>huge</result></task-notification>'),
    userLine({ type: 'text', text: 'array content is a tool result, not a prompt' }),
    // A compaction summary is a user line but machine-authored recap text; the
    // turns it recaps are still on disk and already projected.
    { type: 'user', uuid: 'c1', timestamp: '2026-01-01T00:00:00.000Z', cwd: 'F:\\Project\\Demo', sessionId: 's1',
      message: { role: 'user', content: 'This session is being continued from a previous conversation…', isCompactSummary: true } },
    userLine('<command-name>/graphify</command-name>\n<command-message>graphify</command-message>\n<command-args>F:\\Project\\X --mode deep</command-args>'),
    userLine('真正的提问'),
  ])
  try {
    const store = stubStore()
    await new TranscriptSource(root).sync(store, 'T')
    const prompts = store.projected.filter(event => event.type === 'user/message').map(event => event.data.content[0].text)
    // `/model` with no args is housekeeping; `/graphify <path>` is the intent.
    assert.deepEqual(prompts, ['/graphify F:\\Project\\X --mode deep', '真正的提问'])
  } finally { await cleanup() }
})

