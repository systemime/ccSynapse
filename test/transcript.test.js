test('one API message split across lines collapses to one assistant card', async () => {
  const { root, cleanup } = await fixture([
    userLine('问题'),
    assistantLine('msg_a', 0, { type: 'thinking', thinking: 'hmm' }),
    assistantLine('msg_a', 1, { type: 'text', text: '第一段' }),
    assistantLine('msg_a', 2, { type: 'tool_use', id: 'toolu_1', name: 'Read', input: { file_path: 'x' } }),
    assistantLine('msg_a', 3, { type: 'tool_use', id: 'toolu_2', name: 'Bash', input: { command: 'ls' } }),
    { type: 'user', uuid: 'r1', timestamp: '2026-01-01T00:00:02.000Z', cwd: 'F:\\Project\\Demo', sessionId: 's1',
      message: { role: 'user', content: [{ type: 'tool_result', tool_use_id: 'toolu_1', content: 'file body' }] }, toolUseResult: { type: 'text' } },
  ])
  try {
    const store = stubStore()
    await new TranscriptSource(root).sync(store, 'T')
    const assistants = store.projected.filter(event => event.type === 'assistant/message')
    assert.equal(assistants.length, 1, 'text blocks of one message.id are one card')
    assert.equal(assistants[0].data.message.content[0].text, '第一段')
    assert.equal(assistants[0].data.turn, 1, 'stamped with the turn it answers')

    const calls = store.projected.filter(event => event.type === 'tool/call')
    assert.deepEqual(calls.map(call => call.data.callId), ['toolu_1', 'toolu_2'])
    assert.deepEqual(calls.map(call => call.data.turn), [1, 1], 'turn/step let the store fold tools into this turn')

    const [result] = store.projected.filter(event => event.type === 'tool/result')
    assert.equal(result.data.message.source.callId, 'toolu_1', 'paired to its call by callId')
    assert.equal(result.data.message.content[0].text, 'file body')
    // Without a matching turn/step the store cannot find the card to fold the
    // result into, and every tool ends up with result: null on the canvas.
    assert.equal(result.data.turn, 1)
    assert.equal(result.data.step, 1)
    assert.deepEqual(
      [calls[0].data.turn, calls[0].data.step],
      [result.data.turn, result.data.step],
      'a result is stamped exactly like the call it answers',
    )

    // End-to-end through the store: the call and its result become one record.
    const store2 = (await import('../server/workspace-store.js')).WorkspaceStore
    const directory = await mkdtemp(join(tmpdir(), 'ccsynapse-store-'))
    const workspaceStore = new store2(join(directory, 'state.json'))
    const session = { id: 'sess', title: 'T', header: { cwd: 'F:\\Project\\Demo' }, firstLiveSeq: 0, events: store.projected }
    const thread = await workspaceStore.projectSession(session, 0, 'T')
    const folded = thread.messages.flatMap(message => message.process ?? [])
    assert.equal(folded.length, 2)
    assert.deepEqual(folded.map(item => [item.callId, item.result]), [['toolu_1', 'file body'], ['toolu_2', null]])
    assert.equal(thread.pendingProcess.length, 0, 'nothing left stranded')
    await rm(directory, { recursive: true, force: true })
  } finally { await cleanup() }
})

test('appended lines project incrementally, keeping seq monotonic', async () => {
  const { root, file, cleanup } = await fixture([userLine('第一问')])
  try {
    const store = stubStore()
    const source = new TranscriptSource(root)
    await source.sync(store, 'T')
    assert.deepEqual(store.calls.map(call => call[0]), ['session'], 'first sighting replays whole')

    await appendFile(file, `${JSON.stringify(userLine('第二问'))}\n`, 'utf8')
    await source.sync(store, 'T')
    assert.deepEqual(store.calls.map(call => call[0]), ['session', 'events'], 'later polls feed only the tail')
    const appended = store.projected.filter(event => event.type === 'user/message' && event.data.content[0].text === '第二问')
    assert.equal(appended.length, 1)
  } finally { await cleanup() }
})

test('oversized tool payloads are capped so the state file stays bounded', async () => {
  const huge = 'x'.repeat(88_393)   // the largest single argument measured on disk
  const { root, cleanup } = await fixture([
    userLine('问题'),
    assistantLine('msg_big', 0, { type: 'text', text: 'ok' }),
    assistantLine('msg_big', 1, { type: 'tool_use', id: 'toolu_big', name: 'Write', input: { content: huge } }),
    { type: 'user', uuid: 'r9', timestamp: '2026-01-01T00:00:03.000Z', cwd: 'F:\\Project\\Demo', sessionId: 's1',
      message: { role: 'user', content: [{ type: 'tool_result', tool_use_id: 'toolu_big', content: huge }] }, toolUseResult: {} },
  ])
  try {
    const store = stubStore()
    await new TranscriptSource(root).sync(store, 'T')
    const call = store.projected.find(event => event.type === 'tool/call')
    const result = store.projected.find(event => event.type === 'tool/result')
    assert.ok(call.data.arguments.length < 2_100, `argument capped, got ${call.data.arguments.length}`)
    assert.ok(result.data.message.content[0].text.length < 2_100, 'result capped')
    assert.match(call.data.arguments, /已截断）$/)
  } finally { await cleanup() }
})

test('a trailing assistant message is held one poll, then released', async () => {
  const { root, cleanup } = await fixture([
    userLine('问题'),
    assistantLine('msg_z', 0, { type: 'text', text: '还在写' }),
  ])
  try {
    const store = stubStore()
    const source = new TranscriptSource(root)
    await source.sync(store, 'T')
    // Held: the group touches EOF, so more text of the same message may follow.
    assert.equal(store.projected.filter(event => event.type === 'assistant/message').length, 0)

    await source.sync(store, 'T')   // file unchanged -> the turn is over
    const released = store.projected.filter(event => event.type === 'assistant/message')
    assert.equal(released.length, 1)
    assert.equal(released[0].data.message.content[0].text, '还在写')
  } finally { await cleanup() }
})

