test('detectForks links a child whose leading prompts are a prefix of the parent', () => {
  const sessions = new Map([
    ['parent', { id: 'parent', fingerprint: ['a', 'b'], turnSeqs: [5, 20], lastSeq: 40 }],
    ['child', { id: 'child', fingerprint: ['a', 'b', 'c'], turnSeqs: [5, 20, 31], lastSeq: 50 }],
    ['unrelated', { id: 'unrelated', fingerprint: ['z'], turnSeqs: [3], lastSeq: 9 }],
  ])
  const forks = detectForks(sessions)
  assert.deepEqual([...forks.keys()], ['child'])
  // seedLength is in the PARENT's seq space: the boundary sits at the parent's
  // next turn, so exactly the two shared turns stay inside the fork cut.
  assert.deepEqual(forks.get('child'), { parentSessionId: 'parent', seedLength: 40 })
})

test('a fork is linked but a re-asked question is not, end to end', async () => {
  // A `--fork-session` copy preserves replies verbatim; re-sending the same
  // prompt in a fresh session produces a different answer. Both look identical
  // if you fingerprint only the questions, which is what made two ordinary
  // retries show up as branches on a real corpus.
  const root = await mkdtemp(join(tmpdir(), 'ccsynapse-fork-'))
  const project = join(root, 'F--Project-Demo')
  await mkdir(project, { recursive: true })
  const write = async (id, lines, extra = []) => writeFile(join(project, `${id}.jsonl`), [...lines, ...extra].map(line => `${JSON.stringify(line)}\n`).join(''), 'utf8')

  const turn = (prompt, answer) => [
    userLine(prompt),
    assistantLine(prompt, 0, { type: 'text', text: answer }),
    // A new prompt closes the previous turn, so give each turn a successor.
  ]
  const close = () => [userLine('下一问'), assistantLine('下一问', 0, { type: 'text', text: '下一答' })]

  const t1 = turn('q1', 'a1')
  const t2 = turn('q2', 'a2')
  await write('parent000-0000-0000-0000-000000000000', [...t1, ...t2, ...close()])
  // Fork: identical history, one extra turn appended.
  await write('child0000-0000-0000-0000-000000000000', [...t1, ...t2, ...close(), userLine('分支的新问题')])
  // Retry: same questions, different answers.
  await write('retry0000-0000-0000-0000-000000000000', [
    userLine('q1'), assistantLine('q1', 0, { type: 'text', text: 'DIFFERENT' }),
    userLine('q2'), assistantLine('q2', 0, { type: 'text', text: 'ALSO DIFFERENT' }),
    ...close(),
  ])

  try {
    const source = new TranscriptSource(root)
    await source.sync(stubStore(), 'T')
    const forks = detectForks(source.sessions)
    assert.deepEqual([...forks.keys()], ['child0000-0000-0000-0000-000000000000'],
      'only the verbatim copy is a fork; the retry is not')
    assert.equal(forks.get('child0000-0000-0000-0000-000000000000').parentSessionId, 'parent000-0000-0000-0000-000000000000')
  } finally { await rm(root, { recursive: true, force: true }) }
})

test('detectForks prefers the longest matching parent and ignores non-prefixes', () => {
  const sessions = new Map([
    ['root', { id: 'root', fingerprint: ['a', 'b'], turnSeqs: [1, 8], lastSeq: 25 }],
    ['mid', { id: 'mid', fingerprint: ['a', 'b', 'c'], turnSeqs: [1, 8, 19], lastSeq: 40 }],
    ['leaf', { id: 'leaf', fingerprint: ['a', 'b', 'c', 'd'], turnSeqs: [1, 8, 19, 30], lastSeq: 50 }],
    ['other', { id: 'other', fingerprint: ['a', 'x', 'y'], turnSeqs: [1, 4, 9], lastSeq: 12 }],
  ])
  const forks = detectForks(sessions)
  assert.equal(forks.get('leaf').parentSessionId, 'mid', 'longest shared prefix wins, not root')
  assert.equal(forks.get('mid').parentSessionId, 'root')
  assert.equal(forks.has('other'), false, 'a diverging second prompt is not a fork')
})

test('detectForks needs more than one shared turn, so a common opener is not a fork', () => {
  // "你好" opens many unrelated sessions; one shared turn must not link them.
  const sessions = new Map([
    ['first', { id: 'first', fingerprint: ['hi', 'a'], turnSeqs: [1, 8], lastSeq: 20 }],
    ['second', { id: 'second', fingerprint: ['hi', 'b'], turnSeqs: [1, 8], lastSeq: 20 }],
  ])
  assert.equal(detectForks(sessions).size, 0)
  assert.equal(detectForks(sessions, 1).size, 0, 'neither is a strict prefix of the other')
})

test('detectForks uses UUID intersection when available, never misidentifies a retry', async () => {
  // Fork: the child is a stale snapshot, so it holds a SUBSET of the parent's
  // UUIDs — the original is the one that kept appending.
  const parentUuids = new Set(['u1', 'u2', 'u3', 'u4', 'u5'])
  const childUuids  = new Set(['u1', 'u2', 'u3'])               // subset
  const retryUuids  = new Set(['r1', 'r2', 'r3'])               // disjoint

  const sessions = new Map([
    ['parent', { id: 'parent', uuidSet: parentUuids, fingerprint: [], turnSeqs: [], lastSeq: 50 }],
    ['child',  { id: 'child',  uuidSet: childUuids,  fingerprint: [], turnSeqs: [], lastSeq: 30 }],
    ['retry',  { id: 'retry',  uuidSet: retryUuids,  fingerprint: [], turnSeqs: [], lastSeq: 30 }],
  ])
  const forks = detectForks(sessions)
  assert.deepEqual([...forks.keys()], ['child'], 'only the UUID-subset is a fork')
  assert.equal(forks.get('child').parentSessionId, 'parent')
  assert.equal(forks.has('retry'), false, 'disjoint UUIDs are never a fork')
  assert.equal(forks.has('parent'), false, 'the original is never a child')
})

test('detectForks assigns the larger session as parent, so snapshots are siblings', () => {
  // A fork is a snapshot of the original: the original keeps growing, so it
  // holds MORE uuids. Three snapshots taken at different times all descend
  // from that one original — they must be siblings, not a chain.
  const core = ['u1', 'u2', 'u3', 'u4', 'u5']
  const sessions = new Map([
    ['origin', { id: 'origin', uuidSet: new Set([...core, 'o1', 'o2', 'o3', 'o4', 'o5', 'o6', 'o7', 'o8']), fingerprint: [], turnSeqs: [], lastSeq: 100 }],
    ['snapA',  { id: 'snapA',  uuidSet: new Set(core), fingerprint: [], turnSeqs: [], lastSeq: 30 }],
    ['snapB',  { id: 'snapB',  uuidSet: new Set([...core, 'o1', 'o2']), fingerprint: [], turnSeqs: [], lastSeq: 50 }],
  ])
  const forks = detectForks(sessions)
  assert.equal(forks.get('snapA')?.parentSessionId, 'origin')
  assert.equal(forks.get('snapB')?.parentSessionId, 'origin')
  assert.equal(forks.has('origin'), false, 'the original is never a child')
})
